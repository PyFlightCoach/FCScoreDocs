#!/usr/bin/env python3
"""Generate docs/downgrades/<discipline>.md from FCScore's Tuning package data.

Source: <tuning>/src/tuning/data/<discipline>/ (descriptions.json,
judging_guide.json, RULEBOOK.md, intra_downgrades.csv, box_downgrades.csv,
default_mps.csv). Stdlib only.

Usage:
    python scripts/generate_downgrades.py [--tuning PATH] [--out DIR] [--check]

--check renders in memory and exits 1 if any page differs from the committed
output. The "Generated from Tuning commit" line is ignored in that comparison.

Anchors: each downgrade heading carries its key verbatim as the id
(e.g. {#inter.loop_radius}); each rulebook reference has the id
"rb-<judging_guide key>" (e.g. rb-general.flight_path).
"""
import argparse
import csv
import json
import re
import subprocess
import sys
from pathlib import Path

DISCIPLINES = {"f3a": "F3A", "IMAC": "IMAC", "IAC": "IAC", "IACGlider": "IAC Glider",
               "CIVA": "CIVA", "CIVAGlider": "CIVA Glider"}
COMMIT_PREFIX = "Generated from Tuning commit"
COMMIT_RE = re.compile(r"^" + COMMIT_PREFIX + r".*$", re.M)


class DataError(Exception):
    pass


def read_csv(path, key_col, guide_col):
    """Return ordered list of (key, guide links), skipping # comment lines."""
    with open(path, newline="", encoding="utf-8") as f:
        lines = [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]
    out = []
    for r in csv.DictReader(lines, delimiter=";", skipinitialspace=True):
        r = {k.strip(): (v or "").strip() for k, v in r.items() if k}
        links = [x.strip() for x in r.get(guide_col, "").split(",") if x.strip()]
        out.append((r[key_col], links))
    return out


def git(tuning, *args):
    try:
        return subprocess.run(["git", "-C", str(tuning), *args], check=True,
                              capture_output=True, text=True).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return None


def commit_line(tuning):
    rev = git(tuning, "rev-parse", "--short", "HEAD") or "unknown"
    dirty = git(tuning, "status", "--porcelain", "--", "src/tuning/data")
    return f"{COMMIT_PREFIX}: `{rev}`" + (" (modified)" if dirty else "") + "."


def quote(text):
    return "\n".join("> " + ln if ln.strip() else ">" for ln in text.strip().splitlines())


def rulebook_summary(text):
    """RULEBOOK.md without its title line, as a blockquote."""
    body = text.strip().split("\n", 1)
    return quote(body[1]) if len(body) > 1 else ""


def render(tuning, disc, label):
    d = Path(tuning) / "src" / "tuning" / "data" / disc
    desc = json.loads((d / "descriptions.json").read_text(encoding="utf-8"))
    guide = json.loads((d / "judging_guide.json").read_text(encoding="utf-8"))
    rulebook = (d / "RULEBOOK.md").read_text(encoding="utf-8")

    # Inter-element downgrades are the "inter.*" description keys. default_mps.csv
    # is not the list: some of its parameters are free comparisons or unused
    # defaults with no downgrade (f3a speed, ee_pause), and the pad builder adds
    # pad_length, which has no default. FCScoreFuture's
    # tests/test_downgrade_descriptions.py owns that list. default_mps.csv sets
    # the order and, where a parameter is listed, the judging_guide links.
    mps = dict(read_csv(d / "default_mps.csv", "name", "judging_guide"))
    order = {f"inter.{k}": i for i, k in enumerate(mps)}
    inter_keys = sorted((k for k in desc if k.startswith("inter.")),
                        key=lambda k: (order.get(k, len(order)), k))
    sections = [
        ("Intra-element downgrades",
         read_csv(d / "intra_downgrades.csv", "unique_name", "judging_guide")),
        ("Positioning (box) downgrades",
         read_csv(d / "box_downgrades.csv", "name", "judging_guide")),
        ("Inter-element downgrades",
         [(k, mps.get(k[6:], desc[k].get("rulebook_links", []))) for k in inter_keys]),
    ]

    errors = []
    seen = {}
    for title, items in sections:
        for key, links in items:
            if key in seen:
                errors.append(f"key '{key}' appears twice ({seen[key]} and {title})")
            seen[key] = title
            if key not in desc:
                errors.append(f"CSV key '{key}' ({title}) has no description")
                continue
            dl = desc[key].get("rulebook_links", [])
            if sorted(dl) != sorted(links):
                errors.append(f"'{key}': CSV judging_guide {links} != description "
                              f"rulebook_links {dl}")
    for key, e in desc.items():
        if key not in seen:
            errors.append(f"description key '{key}' is not in any CSV section")
        for link in e.get("rulebook_links", []):
            if link not in guide:
                errors.append(f"'{key}': rulebook link '{link}' not in judging_guide.json")
    if errors:
        raise DataError(f"{disc}:\n  " + "\n  ".join(errors))

    out = [
        "<!-- GENERATED by scripts/generate_downgrades.py from FCScore's Tuning data. "
        "Do not edit. -->",
        "",
        f"# {label} downgrades",
        "",
        "These descriptions are generated from the Tuning package of FCScore and describe what "
        "FCScore measures for each downgrade. See the [downgrade reference](index.md) for how to "
        "read them.",
        "",
        COMMIT_PREFIX + ": `unknown`.",
        "",
        "**Rulebook source**",
        "",
        rulebook_summary(rulebook),
        "",
        "Rulebook extracts are quoted verbatim and listed under "
        "[Rulebook references](#rulebook-references).",
        "",
    ]
    for title, items in sections:
        out += [f"## {title}", ""]
        for key, _ in items:
            e = desc[key]
            out += [f"### {e['name']} {{#{key}}}", "", f"`{key}`", "",
                    e["short_description"].strip(), ""]
            paras = [p.strip() for p in e["long_description"].split("\n\n") if p.strip()]
            if paras:
                out += ['??? note "Details"', ""]
                for p in paras:
                    out += ["    " + " ".join(p.split()), ""]
            for link in e.get("rulebook_links", []):
                g = guide[link]
                out += [quote(g["extract"]), ">", f"> [{g['paragraph']}](#rb-{link})", ""]
    out += ["## Rulebook references", ""]
    for link in sorted(guide, key=lambda k: (guide[k]["paragraph"], k)):
        g = guide[link]
        out += [f"### {g['paragraph']} {{#rb-{link}}}", "", f"`{link}`", "",
                quote(g["extract"]), ""]
    text = "\n".join(out).rstrip() + "\n"
    return COMMIT_RE.sub(lambda m: commit_line(tuning), text, count=1)


def norm(text):
    return COMMIT_RE.sub(COMMIT_PREFIX, text)


def main():
    ap = argparse.ArgumentParser(description="Generate downgrade pages from Tuning data")
    ap.add_argument("--tuning", default="../FCScoreFuture/packages/Tuning")
    ap.add_argument("--out", default="docs/downgrades")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    try:
        pages = {out / f"{disc}.md": render(a.tuning, disc, label)
                 for disc, label in DISCIPLINES.items()}
    except (DataError, OSError, KeyError, json.JSONDecodeError) as ex:
        print(f"ERROR: {ex}", file=sys.stderr)
        return 2
    if a.check:
        bad = [str(p) for p, t in pages.items()
               if not p.exists() or norm(p.read_text(encoding="utf-8")) != norm(t)]
        if bad:
            print("Out of date (run scripts/generate_downgrades.py):\n  " + "\n  ".join(bad),
                  file=sys.stderr)
            return 1
        print("Downgrade pages up to date.")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for p, t in pages.items():
        p.write_text(t, encoding="utf-8")
        print("wrote", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
